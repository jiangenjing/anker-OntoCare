async page=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://cdn.jsdelivr.net/**',r=>r.abort());
 await page.setViewportSize({width:1440,height:1080});
 await page.goto('http://127.0.0.1:5088/benchmark-principles.html');
 await page.locator('#principles.active').waitFor();
 if(await page.locator('script[src]').count())throw Error('Standalone page depends on external script');
 if(await page.locator('#principles .arch-node').count()!==6)throw Error('Missing architecture node');
 await page.locator('#archRed').hover();
 await page.locator('#archTooltip:not([hidden])').waitFor();
 if(!(await page.locator('#archTooltip').innerText()).includes('frustration += 2'))throw Error('Missing tooltip detail');
 await page.locator('#archRed').click();
 if(await page.locator('#group').inputValue()!=='red-team')throw Error('Red filter missing');
 const redCount=await page.locator('#cases tr').count();
 if(redCount===0)throw Error('No real red cases');
 await page.getByRole('tab',{name:'评测原理',exact:true}).click();
 await page.locator('#archBlue').click();
 if(await page.locator('#group').inputValue()!=='blue-team')throw Error('Blue filter missing');
 const blueCount=await page.locator('#cases tr').count();
 await page.getByRole('tab',{name:'评测原理',exact:true}).click();
 await page.locator('#archSources').click();
 await page.locator('.diagram-modal.open').waitFor();
 if(!(await page.locator('#drawerBody').innerText()).includes('P01 · 客诉工单信息 · Excel 第 2 行'))throw Error('Missing source row');
 const evidence=page.locator('#drawerBody [data-case]').first();
 const caseId=await evidence.getAttribute('data-case');await evidence.click();
 if(!(await page.locator('#drawerBody').innerText()).includes('逐轮 Trace 时间轴'))throw Error('Missing real trace');
 await page.keyboard.press('Escape');
 await page.locator('#archReplay').click();
 await page.locator('#archJudge.arch-complete').waitFor();
 await page.getByText('流程示意 · 汇总报告，保留来源与 Trace',{exact:true}).waitFor();
 await page.screenshot({path:'output/playwright/评测原理-桌面.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const rects=await page.locator('#principles').evaluate(e=>({width:document.documentElement.scrollWidth,viewport:innerWidth,red:document.querySelector('#archRed').getBoundingClientRect().bottom,blue:document.querySelector('#archBlue').getBoundingClientRect().top}));
 if(rects.width>rects.viewport||rects.blue<rects.red)throw Error('Mobile layout overflow or not stacked: '+JSON.stringify(rects));
 await page.screenshot({path:'output/playwright/评测原理-手机.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#archReplay').click();
 if(await page.locator('#archReplay').isDisabled())throw Error('Reduced motion playback stuck');
 if(errors.length)throw Error(errors.join(';'));
 return {redCount,blueCount,sourceCase:caseId,mobile:rects,externalScripts:0,pageErrors:errors};
}
